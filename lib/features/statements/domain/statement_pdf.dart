const _months = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/// Signature of [buildStatementPdf]; a provider holds it so tests can substitute a synchronous one.
typedef StatementPdfBuilder = Future<Uint8List> Function({
  required BankAccount account,
  required DateTime month,
  required List<Transaction> transactions,
  required String customerName,
  required DateTime generatedAt,
});

String _two(int n) => n.toString().padLeft(2, '0');

String _money(double v) {
  final fixed = v.abs().toStringAsFixed(2);
  final parts = fixed.split('.');
  final whole = parts[0].replaceAllMapped(RegExp(r'\B(?=(\d{3})+(?!\d))'), (_) => ',');
  return '${v < 0 ? '-' : ''}$whole.${parts[1]}';
}

/// The built-in PDF fonts only cover Latin-1, so anything else is replaced rather than drawn as a blank box.
String pdfSafe(String s) => s
    .replaceAll(RegExp('[‒-―]'), '-')
    .replaceAll(RegExp('[‘’]'), "'")
    .replaceAll(RegExp('[“”]'), '"')
    .replaceAll('•', '*')
    .replaceAll('…', '...')
    .replaceAll(RegExp(r'[^\x20-\x7E -ÿ]'), '?');

String statementPdfFileName(BankAccount account, DateTime month) => statementFileName(account, month).replaceFirst(RegExp(r'\.csv$'), '.pdf');

/// A printable monthly statement. Deterministic for a given input and [generatedAt], so it can be tested byte-for-structure.
Future<Uint8List> buildStatementPdf({
  required BankAccount account,
  required DateTime month,
  required List<Transaction> transactions,
  required String customerName,
  required DateTime generatedAt,
}) async {
  final summary = summarize(transactions);
  final doc = pw.Document(title: 'Statement ${_months[month.month - 1]} ${month.year}', author: 'Zentrix Bank', creator: 'Zentrix Bank app');
  const accent = PdfColor.fromInt(0xFF0C6B86);
  const muted = PdfColor.fromInt(0xFF52607F);

  pw.Widget kv(String k, String v, {bool bold = false}) => pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 2),
    child: pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Text(pdfSafe(k), style: const pw.TextStyle(color: muted)),
        pw.Text(pdfSafe(v), style: pw.TextStyle(fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal)),
      ],
    ),
  );

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(36),
      header: (_) => pw.Container(
        padding: const pw.EdgeInsets.only(bottom: 8),
        margin: const pw.EdgeInsets.only(bottom: 12),
        decoration: const pw.BoxDecoration(border: pw.Border(bottom: pw.BorderSide(color: accent, width: 1.5))),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text('Zentrix Bank', style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold, color: accent)),
            pw.Text('Account statement', style: const pw.TextStyle(color: muted)),
          ],
        ),
      ),
      footer: (ctx) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            'Prototype statement generated by the Zentrix Bank app. It is not an official bank record.',
            style: const pw.TextStyle(fontSize: 8, color: muted),
          ),
          pw.Align(alignment: pw.Alignment.centerRight, child: pw.Text('Page ${ctx.pageNumber} of ${ctx.pagesCount}', style: const pw.TextStyle(fontSize: 8, color: muted))),
        ],
      ),
      build: (_) => [
        pw.Text(pdfSafe(customerName), style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold)),
        pw.SizedBox(height: 4),
        kv('Account', '${account.name}  ${account.maskedNumber}'),
        kv('Period', '${_months[month.month - 1]} ${month.year}'),
        kv('Generated', '${generatedAt.year}-${_two(generatedAt.month)}-${_two(generatedAt.day)} ${_two(generatedAt.hour)}:${_two(generatedAt.minute)}'),
        pw.SizedBox(height: 10),
        pw.Container(
          padding: const pw.EdgeInsets.all(10),
          decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfColors.grey400), borderRadius: pw.BorderRadius.circular(6)),
          child: pw.Column(
            children: [
              kv('Money in', '${account.currency} ${_money(summary.moneyIn)}'),
              kv('Money out', '${account.currency} ${_money(summary.moneyOut)}'),
              kv('Net', '${account.currency} ${_money(summary.net)}', bold: true),
              kv('Transactions', '${summary.count}'),
            ],
          ),
        ),
        pw.SizedBox(height: 14),
        if (transactions.isEmpty)
          pw.Text('There are no settled transactions for this account and month.', style: const pw.TextStyle(color: muted))
        else
          pw.TableHelper.fromTextArray(
            headers: ['Date', 'Description', 'Method', 'Amount (${account.currency})'],
            data: [
              for (final t in transactions)
                [
                  '${t.date.year}-${_two(t.date.month)}-${_two(t.date.day)}',
                  pdfSafe(t.merchant),
                  pdfSafe(t.method),
                  _money(t.amount),
                ],
            ],
            headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white, fontSize: 9),
            headerDecoration: const pw.BoxDecoration(color: accent),
            cellStyle: const pw.TextStyle(fontSize: 9),
            cellAlignments: {0: pw.Alignment.centerLeft, 1: pw.Alignment.centerLeft, 2: pw.Alignment.centerLeft, 3: pw.Alignment.centerRight},
            columnWidths: {0: const pw.FixedColumnWidth(62), 1: const pw.FlexColumnWidth(3), 2: const pw.FlexColumnWidth(2), 3: const pw.FixedColumnWidth(84)},
            oddRowDecoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF2F5FB)),
            border: null,
          ),
      ],
    ),
  );
  return doc.save();
}
